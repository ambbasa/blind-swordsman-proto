    kills: 0,
    coin0: Number(save.coins ?? 0),
    bursts: [],
    lastBurst: 0,
    sightWave: 0,
    lastStrokeDir: null,
    hitstop: 0,
    hurtFlash: 0,
    aimTarget: null,
    bellPans: [],
    recoil: null,
    ringR: 0,
    ringLv: 0,
    bounce: null,
    landRipple: null,
    spiritCap: opts.sandbox ? (cfg.spiritCapStart ?? 1) : Math.max(1, st.spiritCap || (cfg.spiritCapStart ?? 1)),
    charge: 0,
    chargeLv: 0,
    magnetR: cfg.magnetR || 2.2,
    parryCd: 0,
    parryFlash: 0,
    parryHits: [],
    cleaveFx: 0,
