    lastDash: null,
    shake: 0,
    cam: { x: 0, z: 0 },
    dashElem: null,
    elemLv: {},
    tempElem: null,
    dashQuality: 0,
    bellT: 0,
    bellShape: null,
    slowT: 0,
    mapId,
    mapStage: stageNo,
    runNo: 1,
    pool: shapeUnlock.slice(),
